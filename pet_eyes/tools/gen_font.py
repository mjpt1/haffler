"""Generate 4-bit anti-aliased bitmap fonts (Latin + Persian presentation forms)
for the pet firmware. Output: pet_eyes/font_fa.h

Usage: python tools/gen_font.py [path-to-ttf]
Default font: C:/Windows/Fonts/tahoma.ttf (has Persian presentation forms).
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "C:/Windows/Fonts/tahoma.ttf"
OUT = Path(__file__).resolve().parent.parent / "pet_eyes" / "font_fa.h"
SIZES = {"faSmall": 15, "faBig": 24}

cps = set(range(0x20, 0x7F))                 # ASCII
cps |= set(range(0x06F0, 0x06FA))            # Persian digits
cps |= {0x060C, 0x061B, 0x061F, 0x00AB, 0x00BB, 0x066A, 0x2022, 0x00B0}  # ، ؛ ؟ « » ٪ • °
cps |= set(range(0x0621, 0x063B)) | set(range(0x0641, 0x064B))  # base Arabic letters
cps |= {0x067E, 0x0686, 0x0698, 0x06A9, 0x06AF, 0x06CC}          # پ چ ژ ک گ ی
cps |= set(range(0xFE80, 0xFEFD))            # Arabic presentation forms B
cps |= set(range(0xFB56, 0xFB5A)) | set(range(0xFB7A, 0xFB7E))   # پ چ
cps |= set(range(0xFB8A, 0xFB96)) | set(range(0xFBFC, 0xFC00))   # ژ ک گ ی


def missing_mask(font):
    return bytes(font.getmask(chr(0xE000)))


def render(font, cp):
    ch = chr(cp)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    adv = round(font.getlength(ch))
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    if w == 0 or h == 0:
        return dict(cp=cp, xo=0, yo=0, w=0, h=0, adv=adv, bits=b"")
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    px = img.tobytes()
    out = bytearray()
    for i in range(0, len(px), 2):
        a = px[i] >> 4
        b = (px[i + 1] >> 4) if i + 1 < len(px) else 0
        out.append((a << 4) | b)
    return dict(cp=cp, xo=x0, yo=y0, w=w, h=h, adv=adv, bits=bytes(out))


lines = [
    "#pragma once",
    "// Generated by tools/gen_font.py from " + Path(FONT).name + " - do not edit.",
    "#include <stdint.h>",
    "struct FaGlyph { uint16_t cp; int8_t xo, yo; uint8_t w, h, adv; uint32_t off; };",
    "struct FaFont { const FaGlyph *glyphs; uint16_t count; const uint8_t *bits; int8_t ascent; uint8_t lineH; };",
]
for name, size in SIZES.items():
    font = ImageFont.truetype(FONT, size)
    miss = missing_mask(font)
    glyphs, blob, skipped = [], bytearray(), []
    for cp in sorted(cps):
        if cp > 0x7F and bytes(font.getmask(chr(cp))) == miss:
            skipped.append(hex(cp))
            continue
        g = render(font, cp)
        g["off"] = len(blob)
        blob += g["bits"]
        glyphs.append(g)
    ascent, descent = font.getmetrics()
    lines.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(blob), 24):
        lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const FaGlyph {name}_glyphs[] = {{")
    for g in glyphs:
        lines.append(f"  {{0x{g['cp']:04X},{g['xo']},{g['yo']},{g['w']},{g['h']},{g['adv']},{g['off']}}},")
    lines.append("};")
    lines.append(f"static const FaFont {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, {ascent}, {ascent + descent}}};")
    print(f"{name}: {len(glyphs)} glyphs, {len(blob)} bytes, missing {len(skipped)}: {' '.join(skipped[:20])}")

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT)
